from __future__ import annotations

import logging
from typing import Protocol

from huggingface_hub import InferenceClient

logger = logging.getLogger(__name__)


class AIClientError(Exception):
    """Error configuring or calling the AI provider."""


class ModelClient(Protocol):
    """Contract shared by every provider: input=prompt, output=text"""

    name: str

    def complete(self, prompt: str) -> str: ...


class MockClient:
    """Deterministic client used in tests and CI. It never calls the network"""

    name = "mock"

    def complete(self, prompt: str) -> str:
        return "[mock] Explanation not generated by a real model."


class HFClient:
    """Hugging Face Inference Providers client (chat completion task)"""

    name = "hf"

    def __init__(
        self,
        model: str,
        token: str,
        inference_provider: str | None = None,
        max_tokens: int = 500,
        timeout: float = 30.0,
    ) -> None:
        self.model = model
        self.max_tokens = max_tokens
        # inference_provider=None lets Hugging Face choose; "groq", "publicai"...
        # forces one. The token can be a Hugging Face token or the provider's key
        self._client = InferenceClient(
            model=model, provider=inference_provider, token=token, timeout=timeout
        )

    def complete(self, prompt: str) -> str:
        try:
            response = self._client.chat_completion(
                messages=[{"role": "user", "content": prompt}],
                max_tokens=self.max_tokens,
                temperature=0.0,
            )
            return response.choices[0].message.content or ""
        except Exception as error: 
            raise AIClientError(f"Hugging Face call failed: {error}") from error


def get_client(
    provider: str = "mock",
    model: str | None = None,
    token: str | None = None,
    inference_provider: str | None = None,
) -> ModelClient:
    """Builds the client chosen by AI_PROVIDER ('mock' or 'hf')"""

    if provider == "mock":
        return MockClient()
    if provider == "hf":
        if not token:
            raise AIClientError("AI_PROVIDER=hf requires HF_TOKEN")
        if not model:
            raise AIClientError("AI_PROVIDER=hf requires HF_MODEL (owner/name)")
        return HFClient(model=model, token=token, inference_provider=inference_provider)
    raise AIClientError(f"Unknown AI provider: {provider!r}")


if __name__ == "__main__":
    import os

    from dotenv import load_dotenv

    logging.basicConfig(
        level="INFO", format="%(asctime)s %(levelname)s %(name)s %(message)s"
    )
    load_dotenv()

    try:
        client = get_client(
            provider=os.getenv("AI_PROVIDER", "mock"),
            model=os.getenv("HF_MODEL"),
            token=os.getenv("HF_TOKEN"),
            inference_provider=os.getenv("HF_INFERENCE_PROVIDER") or None,
        )
        print(f"Client: {client.name}")
        answer = client.complete("Reply with one short sentence: what is a satellite?")
        print(answer or "(empty response: if the model reasons, raise max_tokens)")
    except AIClientError as error:
        print(f"ERROR: {error}")